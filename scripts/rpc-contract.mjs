#!/usr/bin/env node
// RPC 契约单源生成器。
//
// 一张表（lib/rpc-contract.js）生成两张脸（lib/typert.js、lib/client.js 的 descriptor 段），
// 并校验第三张脸（lib/index.js 的宿主装配）——四张脸的定义与理由见 lib/rpc-contract.js。
//
//   node scripts/rpc-contract.mjs            # 打印差异（--check 的别名，退出码 1 表示不一致）
//   node scripts/rpc-contract.mjs --write    # 重写生成产物
//   node scripts/rpc-contract.mjs --check    # CI：不一致就非零退出
//
// 为什么 @Remote 不生成：装饰器必须贴在各自的方法上（方法体是手写的），整段生成等于把实现也生成
// 出来。R6.1 起宿主那一面改由 `applyRemoteMethods` 按表装配，于是第 1 张脸的**名字与顺序不再有
// 第二份清单**可校对（那正是重构的目的）——这里校验的变成「装配确实用的是那张表」，而"表里的每个
// 名字在原型上都有实现"由装配处的加载期断言 + 第四面用例（运行时原型）各自先一道。
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { INTERNAL_ONLY, MCP_SERVICE, NAMESPACES, splitParam } from '../lib/rpc-contract.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TYPERT_PATH = join(ROOT, 'lib', 'typert.js')
const CLIENT_PATH = join(ROOT, 'lib', 'client.js')
const HOST_PATH = join(ROOT, 'lib', 'index.js')
const CLIENT_BEGIN = '// <rpc-contract:begin> 由 scripts/rpc-contract.mjs 生成，勿手改'
const CLIENT_END = '// <rpc-contract:end>'

/** 生成 lib/typert.js 全文。 */
export function renderTypert() {
  const invocations = []
  for (const { service, methods } of NAMESPACES) {
    const factory = service === MCP_SERVICE ? 'mv' : 'mvs'
    for (const method of methods) {
      const params = method.params.map((param) => {
        const { name, symbol } = splitParam(param)
        return `param('${name}', '${symbol}')`
      })
      invocations.push(`    ${factory}('${method.method}', [${params.join(', ')}], '${method.result}'),`)
    }
  }
  return `/* Generated by scripts/rpc-contract.mjs from lib/rpc-contract.js — do not edit. */
import { z } from 'zod'

const $any = z.unknown()
const $name = z.string()

// strict codec 的形状由宿主校验，而宿主在两个渠道上查**不同的键**：
//   0.1.5-rc.x（= 当时 latest/next，npx 默认装到的那条）查 \`schema\` 必须是 zod v4 实例；
//   0.1.6-alpha.2 起改查 \`create()\` 工厂，不再看 \`schema\`（registry 用
//   \`record.value ??= record.create()\` 在进程内 realm 物化 schema）。
// 两边都忽略对方的键，所以**两个都写**是唯一同时满足基线与 alpha 的形状：少写 \`schema\`
// 会在最新 RC 上加载即拒，少写 \`create\` 会在 alpha 上加载即拒（\`mode: 'src-json'\` 不是出路
// ——loader 强制 invocation 的 codec 必须是 strict）。实测形状矩阵见 docs/design.md「版本
// 范围怎么定」。lib/client.js 的 strictCodec 必须与这里同形状（同一条宿主规则，两处产物）。
const codec = (symbol, schema) => ({
  mode: 'strict',
  typeSymbol: \`dsh-toolbox-ui/typert#\${symbol}\`,
  schema,
  create: () => schema,
})

/**
 * 参数 codec：字符串参数用 z.string()（面板传的是名字），其余按不透明对象处理。
 * 参数名会进 wire，客户端按名字填——所以声明必须与网关签名逐字一致。
 */
const param = (name, symbol) => ({
  name,
  wire: name,
  source: 'json',
  codec: codec(symbol, symbol === 'String' ? $name : $any),
})

/**
 * MCP 服务的 invocation 工厂（服务名见 lib/rpc-contract.js 的 MCP_SERVICE）。
 *
 * 为什么不复用 mvs()：mv() 把 id/service/namespace 三处都写死成同一个服务名（三处必须一致，
 * 所以留一个工厂一种形态是刻意的）。两个服务的 serviceKey 与 wire namespace 都不同
 * （MCP_SERVICE / skillsManager），硬套 mv() 只会得到 id 与实际 endpoint 不符的条目——
 * 那种错误在结构上完全合法，只在调用时静默打到错的服务上。故参数化 service/namespace。
 */
const mv = (method, params, resultSym) => ({
  id: \`dsh-toolbox-ui#${MCP_SERVICE}/\${method}\`,
  service: '${MCP_SERVICE}',
  namespace: '${MCP_SERVICE}',
  method,
  invocation: { kind: 'direct' },
  parameters: params,
  result: codec(resultSym, $any),
  sourceLocation: { file: 'dsh-toolbox-ui/lib/typert.js', line: 7, column: 1 },
})

/** skillsManager 的 invocation 工厂（理由同上：serviceKey 与 namespace 必须都是 skillsManager）。 */
const mvs = (method, params, resultSym) => ({
  id: \`dsh-toolbox-ui#skillsManager/\${method}\`,
  service: 'skillsManager',
  namespace: 'skillsManager',
  method,
  invocation: { kind: 'direct' },
  parameters: params,
  result: codec(resultSym, $any),
  sourceLocation: { file: 'dsh-toolbox-ui/lib/typert.js', line: 7, column: 1 },
})

export const TYPERT = {
  package: 'dsh-toolbox-ui',
  face: 'host',
  schemas: [],
  invocations: [
${invocations.join('\n')}
  ],
  model: { services: [], events: [], objects: [] },
}
`
}

/** 生成 client.js 的 descriptor 段（不含首尾换行）。 */
export function renderClientRegion() {
  const lines = []
  for (const { service, methods } of NAMESPACES) {
    for (const method of methods) {
      const params = method.params.map((param) => {
        const { name, symbol } = splitParam(param)
        return service === MCP_SERVICE ? `mcpParam('${name}', '${symbol}')` : `skParam('${name}', '${symbol}')`
      })
      if (service === MCP_SERVICE) {
        lines.push(`    { id: 'dsh-toolbox-ui#${MCP_SERVICE}/${method.method}', service: '${MCP_SERVICE}', namespace: '${MCP_SERVICE}', method: '${method.method}', invocation: { kind: 'direct' }, parameters: [${params.join(', ')}], result: mcpCodec('${method.result}') },`)
      } else {
        lines.push(`    sk('${method.method}', [${params.join(', ')}], '${method.result}'),`)
      }
    }
  }
  return lines.join('\n')
}

function replaceRegion(text, begin, end, body, label) {
  const start = text.indexOf(begin)
  const stop = text.indexOf(end)
  if (start < 0 || stop < 0 || stop < start) throw new Error(`${label} 里找不到生成区间标记（${begin} … ${end}）`)
  const head = text.slice(0, start + begin.length)
  const tail = text.slice(stop)
  return `${head}\n${body}\n    ${tail}`
}

/** 从 index.js 读手写的 @Remote 名字清单（R6.1 之后应当为空：名字与顺序只在契约表里）。 */
export function readHostRemoteOrder(source) {
  return [...source.matchAll(/Remote\("([A-Za-z0-9_]+)"\)/g)].map((match) => match[1])
}

/** 校验宿主那一面：wire 方法的名字与顺序来自同一份定义。
 *
 * R6.1 起宿主的装饰器不再逐方法手写（`_x = [Remote("x")]` + `__esDecorate(...)`），而是由
 * `lib/remote-wiring.js` 的 `applyRemoteMethods` 按表装配：于是"名字清单与表不一致"这类故障
 * 在结构上不再存在（抄错一个字的机会没了），这里改成校验「确实走的是那张表」：
 *
 *   · 不得残留 `Remote("…")` 字面量——残留就是两处登记同一件事；`mark()` 会对同名标记静默
 *     去重，两处不一致时谁生效取决于执行顺序，正是最难查的那种漂移；
 *   · 两个 gateway 各装配一次，参数分别是 MCP_METHODS / SKILL_METHODS。
 *
 * 「表里的名字在原型上都有实现」由 `applyRemoteMethods` 的加载期断言（不是静默兜底）
 * 与 test/package-contract.test.mjs 的第四面用例（运行时原型）分别先一道。 */
export function checkHostFace(source) {
  const problems = []
  const declared = readHostRemoteOrder(source)
  if (declared.length) {
    problems.push(`宿主仍有 ${declared.length} 处手写 Remote("…")：名字与顺序只在 lib/rpc-contract.js 里，请用 applyRemoteMethods 按表装配`)
    return problems
  }
  const wired = [...source.matchAll(/applyRemoteMethods\(\s*this,\s*(MCP_METHODS|SKILL_METHODS)\b/g)].map((match) => match[1])
  const want = ['MCP_METHODS', 'SKILL_METHODS']
  if (wired.length !== want.length || wired.some((table, index) => table !== want[index])) {
    problems.push(`applyRemoteMethods 的装配点应为 [${want.join(', ')}]，实际 ${wired.length ? `[${wired.join(', ')}]` : '（一处也没有）'}`)
  }
  return problems
}

/** 校验第四面：原型方法集合 = @Remote ∪ INTERNAL_ONLY。由生成器与测试各跑一次。 */
export function checkGatewayFace(gateway, service, source) {
  const expected = NAMESPACES.find((entry) => entry.service === service).methods.map((method) => method.method)
  const internal = new Map(INTERNAL_ONLY)
  const actual = Object.getOwnPropertyNames(gateway.prototype)
    .filter((name) => name !== 'constructor' && !internal.has(name))
  const problems = []
  const offWire = actual.filter((name) => !expected.includes(name))
  if (offWire.length) problems.push(`${service} 原型上这些方法没有进契约：${offWire.join(', ')}`)
  const missing = expected.filter((name) => !actual.includes(name))
  if (missing.length) problems.push(`${service} 契约里这些方法在原型上找不到：${missing.join(', ')}`)
  void source
  return problems
}

function main() {
  const write = process.argv.includes('--write')
  const problems = []
  const typert = renderTypert()
  const currentTypert = readFileSync(TYPERT_PATH, 'utf8')
  if (currentTypert !== typert) {
    if (write) writeFileSync(TYPERT_PATH, typert)
    else problems.push('lib/typert.js 与契约不一致（跑 --write）')
  }
  const client = readFileSync(CLIENT_PATH, 'utf8')
  const nextClient = replaceRegion(client, CLIENT_BEGIN, CLIENT_END, renderClientRegion(), 'lib/client.js')
  if (nextClient !== client) {
    if (write) writeFileSync(CLIENT_PATH, nextClient)
    else problems.push('lib/client.js 的 descriptor 段与契约不一致（跑 --write）')
  }
  problems.push(...checkHostFace(readFileSync(HOST_PATH, 'utf8')))
  if (problems.length) {
    for (const problem of problems) console.error(`✖ ${problem}`)
    process.exitCode = 1
    return
  }
  console.log(`✔ RPC 契约一致（${NAMESPACES.reduce((total, entry) => total + entry.methods.length, 0)} 个方法）`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
